#!/usr/bin/env python3
"""Writes scripts/game-test/crazy-keys.toml: seeded key mashing (user test 5's "going crazy with the keys").

Cases in G1_8 seed 1 (grid identical to the client's): teleport to a spot, then a random sequence of WASD changes,
Space taps and holds, and held clicks with a moving cursor. Compare with `runtime/replay/linediv.py` afterwards:
the scenario itself checks little, the proof is 0 divergence runs between the client's lines and the server's points.
"""
import random, sys, pathlib

SPOTS = [
    ("open", 754, 594),      # open ground, sprint room
    ("wall row 702", 505, 697),  # the wall of user test 5 f2892-2945
    ("wall corner", 524, 704),
    ("open 2", 700, 612),
    ("wall row 702 again", 515, 699),
    ("passage", 680, 590),
]
KEYS = {"W": 0x57, "A": 0x41, "S": 0x53, "D": 0x44}
CENTER = (1280, 720)


def cursor(rng):
    return (CENTER[0] + rng.randint(-500, 500), CENTER[1] + rng.randint(-350, 350))


def mash(seed, length_ms):
    rng = random.Random(seed)
    held, space, press, out, t = set(), False, None, [], 0
    while t < length_ms:
        r = rng.random()
        if r < 0.28:
            k = rng.choice(list(KEYS))
            if k in held:
                held.discard(k)
                out.append(f"inup:{KEYS[k]:#x}")
            else:
                held.add(k)
                out.append(f"indown:{KEYS[k]:#x}")
        elif r < 0.62:
            out.append("up:0x20 inup:0x20" if space else "indown:0x20 down:0x20")
            space = not space
        elif r < 0.75:
            x, y = cursor(rng)
            if press:
                out.append(f"inrelease:{x},{y}")
                press = None
            else:
                out.append(f"inpress:{x},{y}")
                press = (x, y)
        else:
            x, y = cursor(rng)
            out.append(f"inmove:{x},{y}")
        w = rng.choice([33, 66, 100, 100, 150, 200, 300, 500])
        out.append(f"wait:{w}")
        t += w
    if space:
        out.append("up:0x20 inup:0x20")
    if press:
        out.append(f"inrelease:{press[0]},{press[1]}")
    out += [f"inup:{KEYS[k]:#x}" for k in sorted(held)]
    out.append("wait:1500")
    return " ".join(out)


def main():
    root = pathlib.Path(__file__).resolve().parents[2]
    s = ['# Generated by scripts/re/gen_crazy_keys.py: do not edit.',
         'description = "Key mashing near walls and in the open, client lines recorded (G1_8 seed 1)"',
         'input_mode = "wasd"', '', '[client_env]', 'POE_HOOK_MOVEMENT_LOG = "1"', 'POE_HOOK_PHASE_LOG = "1"', 'POE_HOOK_PATH_LOG = "1"', '', '[server]',
         '"dev.drift_check" = true', '',
         '[[step]]', 'name = "transfer to G1_8 seed 1"', 'cmd = "transfer G1_8 1"', '',
         '[[step]]', 'name = "in G1_8"', 'expect_state = { area = "G1_8" }', 'timeout_s = 60', '']
    rounds = int(sys.argv[1]) if len(sys.argv) > 1 else 2
    n = 0
    for r in range(rounds):
        for name, x, y in SPOTS:
            n += 1
            s += ['[[step]]', f'name = "teleport {n} ({name})"', f'cmd = "teleport {x} {y}"', '',
                  '[[step]]', f'name = "at the spot {n}"', f'expect_state = {{ near = [{x}, {y}, 3] }}', '',
                  '[[step]]', f'name = "mash {n}"', f'keys = "{mash(1000 + n, 9000)}"', '']
    s += ['[[step]]', 'name = "no server errors"', 'reject_log = " ERROR "', '']
    (root / "scripts/game-test/crazy-keys.toml").write_text("\n".join(s))


main()
